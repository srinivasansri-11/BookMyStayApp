/**
 * Hotel Booking Management System
 * Use Case 1: Application Entry & Welcome Message
 *
 * This class represents the entry point of the Hotel Booking application.
 * It demonstrates how a Java program starts execution using the main() method
 * and prints a welcome message to the console.
 *
 * @author Student
 * @version 1.0
 */
public class UseCase1HotelBookingApp {

    /**
     * The main method is the entry point of the application.
     * The JVM invokes this method when the program starts.
     *
     * @param args Command line arguments (not used in this program)
     */
    public static void main(String[] args) {

        System.out.println("====================================");
        System.out.println(" Welcome to Hotel Booking System ");
        System.out.println(" Application Version: v1.0 ");
        System.out.println("====================================");

        System.out.println("Application started successfully.");


        System.out.println("Thank you for using the Hotel Booking System.");
    }
}